def summary_display_label(metric: str) -> str:
    level = SUMMARY_LEVELS.get(metric)
    label = SUMMARY_DISPLAY_LABELS.get(metric, metric)
    if metric == "cycle占比" or level is None or level == 1:
        return label
    return f"{'--' * (level - 1)} {label}"
